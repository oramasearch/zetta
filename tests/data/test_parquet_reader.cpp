// Schema inference reads the metadata only and picks every numeric leaf, typed to
// its natural DataType, skipping the byte_array column.
TEST(ParquetReader, InfersNumericSchema) {
    const std::string bytes = read_bytes(decode_fixture_path());
    const auto inferred = infer_parquet_schema(bytes);
    ASSERT_TRUE(inferred.ok()) << inferred.error;

    std::vector<std::string> names;
    for (const ColumnSchema& column : inferred.schema.columns) names.push_back(column.name);
    // churn_decode columns minus the byte_array `segment`.
    EXPECT_EQ(names, (std::vector<std::string>{"account_id", "risk_score", "score_f32",
                                               "failed_payments", "is_churned", "tenure_days"}));
}

// A malformed file fails the load rather than reading out of bounds.
TEST(ParquetReader, RejectsMalformedBytes) {
    DataFrameSchema schema;
    schema.columns.push_back(ColumnSchema{"x", "", zetta::compute::DataType::Int64});
    CpuDevice device;
    const DataFrameResult result =
        load_parquet_data_frame("not a parquet file", schema, device);
    EXPECT_FALSE(result.ok());
    EXPECT_EQ(result.status.code, ComputeStatusCode::InvalidArgument);
}
