// Native Parquet → DDF reader with column projection (ADR-32 / #508). The
// headline (TC-9 / #499): load a *projected subset* of a saas-sales-conversations
// sample into a DataFrame — the engineered numeric columns + `outcome`, dropping
// the embedding_* columns — and match a pyarrow-built golden DataFrame field for
// field. Plus projection over the independently-built #506 decode fixture, the
// dense/numeric boundary (nulls / byte_array / real-into-int), and schema
// inference. The fixtures + goldens are regenerated by scripts/gen-parquet-
// fixture.py (needs pyarrow, run by hand — no foreign runtime in build/CI).
