// Native Parquet column-chunk decoders (ADR-32 / #506). The acceptance: each
// column type decodes to typed values matching a golden, including definition
// levels for the (mostly non-null) columns we load.
//
// The decode fixture (churn_decode.parquet) is a separate, dedicated file —
// churn_sample.parquet mixes in zstd + gzip to exercise the metadata parser's
// codec identification, but those codecs have no native decompressor yet, so the
// decoder fixture uses only uncompressed + snappy while still spanning every
// encoding (PLAIN + dictionary) and physical type (int32/int64/float/double/
// bool/byte_array), plus a nullable column to exercise definition levels. Both
// the fixture and the values golden are regenerated by scripts/gen-parquet-
// fixture.py (needs pyarrow, run by hand — no foreign runtime in build/CI).
