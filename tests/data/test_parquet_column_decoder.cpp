// Native Parquet column-chunk decoders (ADR-32 / #506). The acceptance: each
// column type decodes to typed values matching a golden, including definition
// levels for the (mostly non-null) columns we load.
//
// The decode fixture (churn_decode.parquet) is a separate, dedicated file —
// churn_sample.parquet mixes in zstd + gzip to exercise the metadata parser's
// codec identification, but those codecs have no native decompressor yet, so the
// decoder fixture uses only uncompressed + snappy while still spanning every
// encoding (PLAIN + dictionary) and physical type (int32/int64/float/double/
// bool/byte_array), plus a nullable column to exercise definition levels. Both
// the fixture and the values golden are regenerated by scripts/gen-parquet-
// fixture.py (needs pyarrow, run by hand — no foreign runtime in build/CI).
namespace {

namespace fs = std::filesystem;
using zetta::parquet::DecodedColumn;
using zetta::parquet::PhysicalType;

fs::path parquet_dir() { return fs::path(ZETTA_TEST_FIXTURES_DIR) / "parquet"; }
fs::path decode_fixture_path() { return parquet_dir() / "churn_decode.parquet"; }
fs::path decode_golden_path() { return parquet_dir() / "churn_decode.values.json"; }
fs::path sample_fixture_path() { return parquet_dir() / "churn_sample.parquet"; }

std::string read_bytes(const fs::path& path) {
    std::ifstream stream(path, std::ios::binary);
    std::ostringstream buffer;
    buffer << stream.rdbuf();
    return buffer.str();
}

nlohmann::json read_json(const fs::path& path) {
    std::ifstream stream(path);
    std::ostringstream buffer;
    buffer << stream.rdbuf();
    return nlohmann::json::parse(buffer.str());
}

// A file whose one REQUIRED int64 column `x` is split into row groups of two
// rows, with the physical type of the LAST row group's chunk rewritten to
// boolean in the footer. The schema still says int64, so the file declares two
// physical types for one leaf (LSR-167). The patch is the compact-protocol
// field header for ColumnMetaData.type (0x15) followed by the zigzag code
// (int64 = 0x04 becomes boolean = 0x00); the caller checks it landed by parsing
// the footer back.
std::string mixed_physical_type_file(std::int64_t rows) {
    std::vector<nlohmann::json> data;
    for (std::int64_t row = 0; row < rows; ++row) data.push_back({{"x", 1000 + row}});
    zetta::parquet::WriterOptions options;
    options.codec = zetta::parquet::CompressionCodec::Uncompressed;
    options.max_rows_per_row_group = 2;
    const auto written = zetta::parquet::write_parquet_rows(
        data, {{"x", PhysicalType::Int64, /*optional=*/false}}, options);
    if (!written.ok()) return {};
    std::string bytes = written.data;

    std::uint32_t footer_length = 0;
    std::memcpy(&footer_length, bytes.data() + bytes.size() - 8, 4);
    const std::size_t footer_start = bytes.size() - 8 - footer_length;
    const std::size_t last_type = bytes.rfind(std::string("\x15\x04"), bytes.size() - 8);
    if (last_type == std::string::npos || last_type < footer_start) return {};
    bytes[last_type + 1] = '\x00';
    return bytes;
}

}  // namespace

// The headline acceptance: decode every column of the fixture and match the
// committed golden values document field for field.
TEST(ParquetColumnDecoder, DecodesAllColumnsMatchingGolden) {
    const std::string bytes = read_bytes(decode_fixture_path());
    ASSERT_FALSE(bytes.empty()) << "missing fixture " << decode_fixture_path();

    const auto meta = zetta::parquet::parse_parquet_metadata(bytes);
    ASSERT_TRUE(meta.ok()) << meta.error;

    const auto leaves = meta.metadata.leaf_columns();
    nlohmann::json columns = nlohmann::json::array();
    for (std::size_t index = 0; index < leaves.size(); ++index) {
        const auto decoded = zetta::parquet::decode_column(bytes, meta.metadata, index);
        ASSERT_TRUE(decoded.ok()) << leaves[index].path << ": " << decoded.error;
        columns.push_back(zetta::parquet::to_json(decoded.column));
    }

    nlohmann::json document = {
        {"num_rows", meta.metadata.num_rows},
        {"columns", std::move(columns)},
    };

    const nlohmann::json golden = read_json(decode_golden_path());
    EXPECT_EQ(document, golden);
}

// The committed golden is external data, so it is validated at the boundary
// against the schema-as-code source of truth before it is trusted.
TEST(ParquetColumnDecoder, GoldenPassesTheSchemaBoundary) {
    const nlohmann::json golden = read_json(decode_golden_path());
    EXPECT_EQ(zetta::parquet::validate_parquet_columns_json(golden), "");
}

TEST(ParquetColumnDecoder, MalformedColumnsJsonFailsTheBoundary) {
    nlohmann::json bad = read_json(decode_golden_path());
    bad["num_rows"] = "lots";  // must be an integer
    EXPECT_NE(zetta::parquet::validate_parquet_columns_json(bad), "");

    nlohmann::json missing = read_json(decode_golden_path());
    missing["columns"][0].erase("values");  // a required field
    EXPECT_NE(zetta::parquet::validate_parquet_columns_json(missing), "");
}

// PLAIN fixed-width / bit-packed decode, typed: int64, double, float, bool.
TEST(ParquetColumnDecoder, DecodesPlainTypedValues) {
    const std::string bytes = read_bytes(decode_fixture_path());
    const auto meta = zetta::parquet::parse_parquet_metadata(bytes);
    ASSERT_TRUE(meta.ok()) << meta.error;

    const auto account = zetta::parquet::decode_column(bytes, meta.metadata, 0);
    ASSERT_TRUE(account.ok()) << account.error;
    EXPECT_EQ(account.column.type, PhysicalType::Int64);
    EXPECT_TRUE(account.column.validity.empty());  // REQUIRED → all present
    EXPECT_EQ(account.column.values.int64_values,
              (std::vector<std::int64_t>{101, 102, 103, 104, 105, 106}));

    const auto risk = zetta::parquet::decode_column(bytes, meta.metadata, 1);
    ASSERT_TRUE(risk.ok()) << risk.error;
    EXPECT_EQ(risk.column.type, PhysicalType::Double);
    ASSERT_EQ(risk.column.values.double_values.size(), 6u);
    EXPECT_DOUBLE_EQ(risk.column.values.double_values[1], 0.92);

    const auto score = zetta::parquet::decode_column(bytes, meta.metadata, 2);
    ASSERT_TRUE(score.ok()) << score.error;
    EXPECT_EQ(score.column.type, PhysicalType::Float);
    EXPECT_EQ(score.column.values.float_values,
              (std::vector<float>{0.5f, 0.25f, 0.75f, 1.0f, 0.125f, 0.625f}));

    const auto churned = zetta::parquet::decode_column(bytes, meta.metadata, 4);
    ASSERT_TRUE(churned.ok()) << churned.error;
    EXPECT_EQ(churned.column.type, PhysicalType::Boolean);
    EXPECT_EQ(churned.column.values.bool_values,
              (std::vector<std::uint8_t>{0, 1, 0, 1, 0, 1}));
}

// Dictionary decode (RLE/bit-packed indices through a PLAIN dictionary page):
// int32 and byte_array.
TEST(ParquetColumnDecoder, DecodesDictionaryEncodedValues) {
    const std::string bytes = read_bytes(decode_fixture_path());
    const auto meta = zetta::parquet::parse_parquet_metadata(bytes);
    ASSERT_TRUE(meta.ok()) << meta.error;

    const auto failed = zetta::parquet::decode_column(bytes, meta.metadata, 3);
    ASSERT_TRUE(failed.ok()) << failed.error;
    EXPECT_EQ(failed.column.type, PhysicalType::Int32);
    EXPECT_EQ(failed.column.values.int32_values,
              (std::vector<std::int32_t>{0, 4, 1, 2, 0, 3}));

    const auto segment = zetta::parquet::decode_column(bytes, meta.metadata, 5);
    ASSERT_TRUE(segment.ok()) << segment.error;
    EXPECT_EQ(segment.column.type, PhysicalType::ByteArray);
    EXPECT_EQ(segment.column.values.byte_array_values,
              (std::vector<std::string>{"smb", "ent", "smb", "ent", "mid", "smb"}));
}

// Definition levels: the OPTIONAL column carries nulls, decoded into a validity
// bitmap; the dense values hold only the present rows in row order.
TEST(ParquetColumnDecoder, DecodesDefinitionLevelsForOptionalColumn) {
    const std::string bytes = read_bytes(decode_fixture_path());
    const auto meta = zetta::parquet::parse_parquet_metadata(bytes);
    ASSERT_TRUE(meta.ok()) << meta.error;

    const auto tenure = zetta::parquet::decode_column(bytes, meta.metadata, 6);
    ASSERT_TRUE(tenure.ok()) << tenure.error;
    EXPECT_EQ(tenure.column.type, PhysicalType::Int64);
    EXPECT_EQ(tenure.column.num_rows, 6);

    // tenure_days = [10, null, 30, 40, null, 60]
    ASSERT_EQ(tenure.column.validity, (std::vector<std::uint8_t>{1, 0, 1, 1, 0, 1}));
    EXPECT_FALSE(tenure.column.row_is_valid(1));
    EXPECT_FALSE(tenure.column.row_is_valid(4));
    EXPECT_EQ(tenure.column.valid_count(), 4);
    // Dense present-only values, in row order (nulls skipped).
    EXPECT_EQ(tenure.column.values.int64_values,
              (std::vector<std::int64_t>{10, 30, 40, 60}));

    // to_json re-expands nulls into the per-row array.
    const nlohmann::json json = zetta::parquet::to_json(tenure.column);
    EXPECT_EQ(json["values"], nlohmann::json({10, nullptr, 30, 40, nullptr, 60}));
}

// A single column chunk (one row group's slice) decodes independently — the
// first row group of the 4 + 2 split holds the first four rows.
TEST(ParquetColumnDecoder, DecodesASingleColumnChunk) {
    const std::string bytes = read_bytes(decode_fixture_path());
    const auto meta = zetta::parquet::parse_parquet_metadata(bytes);
    ASSERT_TRUE(meta.ok()) << meta.error;
    ASSERT_EQ(meta.metadata.row_groups.size(), 2u);

    const auto chunk = zetta::parquet::decode_column_chunk(bytes, meta.metadata, 0, 0);
    ASSERT_TRUE(chunk.ok()) << chunk.error;
    EXPECT_EQ(chunk.column.num_rows, 4);
    EXPECT_EQ(chunk.column.values.int64_values,
              (std::vector<std::int64_t>{101, 102, 103, 104}));
}

