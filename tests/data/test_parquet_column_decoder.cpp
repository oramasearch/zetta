// a chunk whose physical type disagrees with the schema leaf is refused.
// Merging the row groups used to keep the first group's type, append each
// group's values to a different typed vector, and count every row — so the row
// transpose indexed past the end of the int64 vector.
TEST(ParquetColumnDecoder, RejectsAChunkWhosePhysicalTypeDisagreesWithTheSchema) {
    const std::string bytes = mixed_physical_type_file(4);
    ASSERT_FALSE(bytes.empty());
    const auto meta = zetta::parquet::parse_parquet_metadata(bytes);
    ASSERT_TRUE(meta.ok()) << meta.error;
    ASSERT_EQ(meta.metadata.row_groups.size(), 2u);
    ASSERT_EQ(meta.metadata.leaf_columns().at(0).type, PhysicalType::Int64);
    ASSERT_EQ(meta.metadata.row_groups[0].columns[0].type, PhysicalType::Int64);
    ASSERT_EQ(meta.metadata.row_groups[1].columns[0].type, PhysicalType::Boolean);

    const auto first = zetta::parquet::decode_column_chunk(bytes, meta.metadata, 0, 0);
    EXPECT_TRUE(first.ok()) << first.error;

    const auto mismatched = zetta::parquet::decode_column_chunk(bytes, meta.metadata, 1, 0);
    EXPECT_FALSE(mismatched.ok());
    EXPECT_NE(mismatched.error.find("physical type"), std::string::npos) << mismatched.error;

    const auto whole = zetta::parquet::decode_column(bytes, meta.metadata, 0);
    EXPECT_FALSE(whole.ok());
    EXPECT_NE(whole.error.find("physical type"), std::string::npos) << whole.error;

    const auto rows = zetta::parquet::read_parquet_rows(bytes);
    EXPECT_FALSE(rows.ok());
    EXPECT_TRUE(rows.rows.empty());
    EXPECT_NE(rows.error.find("physical type"), std::string::npos) << rows.error;
}

