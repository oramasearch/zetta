// A codec without a native decoder yet (zstd / gzip in the metadata fixture)
// fails with a clear reason rather than producing wrong values — the honest
// binary boundary.
TEST(ParquetColumnDecoder, RejectsUndecodableCodec) {
    const std::string bytes = read_bytes(sample_fixture_path());
    const auto meta = zetta::parquet::parse_parquet_metadata(bytes);
    ASSERT_TRUE(meta.ok()) << meta.error;

    // risk_score is zstd-compressed in churn_sample.parquet.
    const auto risk = zetta::parquet::decode_column(bytes, meta.metadata, 1);
    EXPECT_FALSE(risk.ok());
    EXPECT_NE(risk.error.find("codec"), std::string::npos);
}

// Truncating the file makes a page body run past the end; the decoder fails
// cleanly rather than reading out of bounds.
TEST(ParquetColumnDecoder, RejectsTruncatedPageBytes) {
    std::string bytes = read_bytes(decode_fixture_path());
    const auto meta = zetta::parquet::parse_parquet_metadata(bytes);
    ASSERT_TRUE(meta.ok()) << meta.error;

    // Cut the file to just past the footer-less header region so the first
    // column's pages can no longer be fully read.
    std::string truncated = bytes.substr(0, 8);
    const auto decoded = zetta::parquet::decode_column(truncated, meta.metadata, 0);
    EXPECT_FALSE(decoded.ok());
}

// Out-of-range indices into the metadata are rejected, not dereferenced.
TEST(ParquetColumnDecoder, RejectsOutOfRangeIndices) {
    const std::string bytes = read_bytes(decode_fixture_path());
    const auto meta = zetta::parquet::parse_parquet_metadata(bytes);
    ASSERT_TRUE(meta.ok()) << meta.error;

    EXPECT_FALSE(zetta::parquet::decode_column(bytes, meta.metadata, 99).ok());
    EXPECT_FALSE(zetta::parquet::decode_column_chunk(bytes, meta.metadata, 99, 0).ok());
    EXPECT_FALSE(zetta::parquet::decode_column_chunk(bytes, meta.metadata, 0, 99).ok());
}

// LSR-167: a chunk whose physical type disagrees with the schema leaf is refused.
// Merging the row groups used to keep the first group's type, append each
// group's values to a different typed vector, and count every row — so the row
// transpose indexed past the end of the int64 vector.
TEST(ParquetColumnDecoder, RejectsAChunkWhosePhysicalTypeDisagreesWithTheSchema) {
    const std::string bytes = mixed_physical_type_file(4);
    ASSERT_FALSE(bytes.empty());
    const auto meta = zetta::parquet::parse_parquet_metadata(bytes);
    ASSERT_TRUE(meta.ok()) << meta.error;
    ASSERT_EQ(meta.metadata.row_groups.size(), 2u);
    ASSERT_EQ(meta.metadata.leaf_columns().at(0).type, PhysicalType::Int64);
    ASSERT_EQ(meta.metadata.row_groups[0].columns[0].type, PhysicalType::Int64);
    ASSERT_EQ(meta.metadata.row_groups[1].columns[0].type, PhysicalType::Boolean);

    const auto first = zetta::parquet::decode_column_chunk(bytes, meta.metadata, 0, 0);
    EXPECT_TRUE(first.ok()) << first.error;

    const auto mismatched = zetta::parquet::decode_column_chunk(bytes, meta.metadata, 1, 0);
    EXPECT_FALSE(mismatched.ok());
    EXPECT_NE(mismatched.error.find("physical type"), std::string::npos) << mismatched.error;

    const auto whole = zetta::parquet::decode_column(bytes, meta.metadata, 0);
    EXPECT_FALSE(whole.ok());
    EXPECT_NE(whole.error.find("physical type"), std::string::npos) << whole.error;

    const auto rows = zetta::parquet::read_parquet_rows(bytes);
    EXPECT_FALSE(rows.ok());
    EXPECT_TRUE(rows.rows.empty());
    EXPECT_NE(rows.error.find("physical type"), std::string::npos) << rows.error;
}

// A file with a single row group whose chunk disagrees with the schema is refused
// too: the row-group-at-a-time pager (ParquetStore) decodes chunks one by one.
TEST(ParquetColumnDecoder, RejectsAMismatchedChunkInASingleRowGroup) {
    const std::string bytes = mixed_physical_type_file(2);
    ASSERT_FALSE(bytes.empty());
    const auto meta = zetta::parquet::parse_parquet_metadata(bytes);
    ASSERT_TRUE(meta.ok()) << meta.error;
    ASSERT_EQ(meta.metadata.row_groups.size(), 1u);
    ASSERT_EQ(meta.metadata.row_groups[0].columns[0].type, PhysicalType::Boolean);

    EXPECT_FALSE(zetta::parquet::decode_column_chunk(bytes, meta.metadata, 0, 0).ok());
    EXPECT_FALSE(zetta::parquet::read_parquet_rows(bytes).ok());
}

// The shape check every transpose relies on: one populated vector, of the
// column's type, holding exactly one value per present row.
TEST(ParquetColumnDecoder, ValidatesTheDecodedColumnShape) {
    DecodedColumn column;
    column.path = "x";
    column.type = PhysicalType::Int64;
    column.num_rows = 3;
    column.values.int64_values = {1, 2, 3};
    EXPECT_EQ(zetta::parquet::validate_decoded_column(column), "");

    DecodedColumn short_values = column;
    short_values.values.int64_values = {1};
    EXPECT_NE(zetta::parquet::validate_decoded_column(short_values), "");

    DecodedColumn second_vector = column;
    second_vector.values.bool_values = {1};
    EXPECT_NE(zetta::parquet::validate_decoded_column(second_vector), "");

    DecodedColumn short_validity = column;
    short_validity.validity = {1, 1};
    short_validity.values.int64_values = {1, 2};
    EXPECT_NE(zetta::parquet::validate_decoded_column(short_validity), "");

    DecodedColumn nullable = column;
    nullable.validity = {1, 0, 1};
    nullable.values.int64_values = {1, 3};
    EXPECT_EQ(zetta::parquet::validate_decoded_column(nullable), "");

    DecodedColumn unknown = column;
    unknown.type = PhysicalType::Unknown;
    unknown.values.int64_values.clear();
    unknown.num_rows = 0;
    EXPECT_NE(zetta::parquet::validate_decoded_column(unknown), "");

    // to_json never reads past the dense values of an inconsistent column.
    const nlohmann::json json = zetta::parquet::to_json(short_values);
    EXPECT_EQ(json["values"], nlohmann::json({1, nullptr, nullptr}));
}
