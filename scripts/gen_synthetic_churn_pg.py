"""Generate synthetic churn data in Charles's (Motive) schema into local Postgres (#866).

The churn fork (#853) trains near real-shaped data with no live-Snowflake dependency.
This synthesizes accounts + communications in the EXACT schema recovered from Charles's
two n8n workflows (docs/meetings/2026-06-03-.../charles-n8n-workflows.md):
  - account_registry   : SFDC_ACCOUNT_ID/NAME, FINANCE_SEGMENT/SUB, segment_l1..l5
  - account_events     : per-event EVENT_DATE/TYPE/SYSTEM + COMM_SUBJECT/TEXT + length
  - account_labels     : churned + CHURN_DATE + LAST_CHURN_REASON (the training target)

The point is *learnable signal*: each account gets a latent risk; churned accounts carry
more escalations and more negative communications, so an XGBoost + SHAP model over event
features beats his LLM-only pattern-matching. Communication text is templated by risk
offline, or generated by a frontier model (OpenRouter) with --realistic.

Target DB precedence: DATABASE_URL > --database > PGDATABASE > `orama_churn_synth`
(the explicit default — not libpq's implicit user-named DB). Create it once with
`createdb orama_churn_synth`. Host/user/password come from PG* env either way.

Env-driven (nothing contacted unless you run the insert / --realistic):
  DATABASE_URL or PG* (PGHOST/PGPORT/PGUSER/PGPASSWORD/PGDATABASE)  local Postgres
  OPENROUTER_API_KEY, OPENROUTER_MODEL                              --realistic comms

Usage (always via `uv run`; deps are declared inline above, PEP 723):
  uv run gen_synthetic_churn_pg.py --self-test        # offline: rows + signal present
  uv run gen_synthetic_churn_pg.py --dry-run          # print DDL + a sample account
  uv run gen_synthetic_churn_pg.py --accounts 500     # create schema + insert
"""
from __future__ import annotations

import argparse
import json
import os
import random
import sys
from typing import Any

# Motive's real org structure (from the n8n Batch Config nodes).
SEGMENTS = [
    ("Enterprise", "USA"), ("Enterprise", "Strategic"), ("Enterprise", "CAN"),
    ("MCS", "MM-USA"), ("MCS", "CMRL-USA"), ("MCS", "SMB-USA"),
    ("New Markets", "SMB-CAN"), ("New Markets", "CMRL-CAN"), ("New Markets", "Enterprise-CAN"),
]
EVENT_SYSTEMS = ["salesforce", "gong", "zendesk", "email"]
CHURN_REASONS = ["pricing", "product gaps", "competitor", "service", "budget cut"]

# Communication templates by risk band — the signal a tabular model learns.
CALM = ["Thanks for the quick help.", "Renewal looks good, team is happy.",
        "Great QBR, expanding usage next quarter."]
NEUTRAL = ["Following up on the open ticket.", "Can we schedule a check-in?",
           "Question about the latest invoice."]
ESCALATING = ["This is the third time we've raised this issue.",
              "Leadership is asking why we're still on this platform.",
              "We're evaluating alternatives; the ROI isn't there."]

SCHEMA_DDL = """
CREATE TABLE IF NOT EXISTS account_registry (
    sfdc_account_id     TEXT PRIMARY KEY,
    sfdc_account_name   TEXT NOT NULL,
    finance_segment     TEXT NOT NULL,
    finance_sub_segment TEXT NOT NULL,
    segment_l1          TEXT, segment_l2 TEXT, segment_l3 TEXT,
    segment_l4          TEXT, segment_l5 TEXT
);
CREATE TABLE IF NOT EXISTS account_events (
    sfdc_account_id TEXT NOT NULL REFERENCES account_registry(sfdc_account_id),
    event_date      DATE NOT NULL,
    event_type      TEXT NOT NULL,
    event_system    TEXT NOT NULL,
    comm_subject    TEXT,
    comm_text       TEXT,
    communications_text_length INT
);
CREATE TABLE IF NOT EXISTS account_labels (
    sfdc_account_id   TEXT PRIMARY KEY REFERENCES account_registry(sfdc_account_id),
    churned           BOOLEAN NOT NULL,
    churn_date        DATE,
    last_churn_reason TEXT
);
CREATE INDEX IF NOT EXISTS account_events_by_account ON account_events(sfdc_account_id);
""".strip()


def synth_account(rng: random.Random, index: int, realistic: bool = False) -> dict[str, Any]:
    """Build one synthetic account (registry + events + label) offline & deterministically."""
    segment, sub = rng.choice(SEGMENTS)
    account_id = f"0018{index:07d}"
    risk = rng.betavariate(2, 3)  # latent churn risk in (0,1)
    n_events = rng.randint(4, 24)
    events = []
    negatives = 0
    for _ in range(n_events):
        # More escalations as risk rises.
        band = rng.random()
        if band < risk * 0.7:
            text = rng.choice(ESCALATING)
            event_type = "escalation"
            negatives += 1
        elif band < 0.6:
            text = rng.choice(NEUTRAL)
            event_type = "inquiry"
        else:
            text = rng.choice(CALM)
            event_type = "positive"
        if realistic:
            text = _realistic_comm(segment, event_type)
        events.append({
            "event_date": f"2026-{rng.randint(1, 6):02d}-{rng.randint(1, 28):02d}",
            "event_type": event_type,
            "event_system": rng.choice(EVENT_SYSTEMS),
            "comm_subject": f"{event_type} re {segment}",
            "comm_text": text,
            "communications_text_length": len(text),
        })
    churned = (risk + negatives / max(n_events, 1)) / 2 > 0.5
    return {
        "registry": {
            "sfdc_account_id": account_id,
            "sfdc_account_name": f"Account {index}",
            "finance_segment": segment,
            "finance_sub_segment": sub,
            "segment_l1": segment, "segment_l2": sub, "segment_l3": None,
            "segment_l4": None, "segment_l5": None,
        },
        "events": events,
        "label": {
            "sfdc_account_id": account_id,
            "churned": churned,
            "churn_date": events[-1]["event_date"] if churned else None,
            "last_churn_reason": rng.choice(CHURN_REASONS) if churned else None,
        },
        "_risk": risk,  # inspection only; not persisted
    }


def _realistic_comm(segment: str, event_type: str) -> str:
    key = os.environ["OPENROUTER_API_KEY"]
    model = os.environ.get("OPENROUTER_MODEL", "anthropic/claude-sonnet-4.5")
    import requests  # lazy

    resp = requests.post(
        "https://openrouter.ai/api/v1/chat/completions",
        headers={"Authorization": f"Bearer {key}"},
        json={"model": model, "messages": [{"role": "user", "content": (
            f"Write a 1-2 sentence B2B customer communication for a {segment} logistics "
            f"account, tone matching a '{event_type}' event. Text only.")}]},
        timeout=60,
    )
    resp.raise_for_status()
    return resp.json()["choices"][0]["message"]["content"].strip()


# Explicit, purpose-named default — never libpq's implicit "database named after the
# connecting user", which for a table-creating script is fragile (fails or writes to an
# arbitrary DB). Override with DATABASE_URL, PGDATABASE, or --database. Create it once:
#   createdb orama_churn_synth
DEFAULT_DATABASE = "orama_churn_synth"


def connect(database: str | None):
    """Return (connection, human label). Target precedence: DATABASE_URL > --database >
    PGDATABASE > the explicit default. Host/user/password still come from PG* env."""
    import psycopg2  # lazy

    url = os.environ.get("DATABASE_URL")
    if url:
        return psycopg2.connect(url), url
    dbname = database or os.environ.get("PGDATABASE") or DEFAULT_DATABASE
    return psycopg2.connect(dbname=dbname), f"dbname={dbname}"


def insert(accounts: list[dict[str, Any]], database: str | None = None) -> None:
    conn, label = connect(database)
    print(f"-> Postgres: {label}", file=sys.stderr)
    try:
        with conn, conn.cursor() as cur:
            cur.execute(SCHEMA_DDL)
            for account in accounts:
                reg = account["registry"]
                cur.execute(
                    "INSERT INTO account_registry (sfdc_account_id, sfdc_account_name, "
                    "finance_segment, finance_sub_segment, segment_l1, segment_l2, "
                    "segment_l3, segment_l4, segment_l5) VALUES (%(sfdc_account_id)s, "
                    "%(sfdc_account_name)s, %(finance_segment)s, %(finance_sub_segment)s, "
                    "%(segment_l1)s, %(segment_l2)s, %(segment_l3)s, %(segment_l4)s, "
                    "%(segment_l5)s) ON CONFLICT (sfdc_account_id) DO NOTHING", reg)
                for event in account["events"]:
                    cur.execute(
                        "INSERT INTO account_events (sfdc_account_id, event_date, "
                        "event_type, event_system, comm_subject, comm_text, "
                        "communications_text_length) VALUES (%s, %s, %s, %s, %s, %s, %s)",
                        (reg["sfdc_account_id"], event["event_date"], event["event_type"],
                         event["event_system"], event["comm_subject"], event["comm_text"],
                         event["communications_text_length"]))
                cur.execute(
                    "INSERT INTO account_labels (sfdc_account_id, churned, churn_date, "
                    "last_churn_reason) VALUES (%(sfdc_account_id)s, %(churned)s, "
                    "%(churn_date)s, %(last_churn_reason)s) ON CONFLICT (sfdc_account_id) "
                    "DO NOTHING", account["label"])
    finally:
        conn.close()


def self_test() -> int:
    rng = random.Random(7)
    accounts = [synth_account(rng, i) for i in range(200)]
    required = {"sfdc_account_id", "finance_segment", "finance_sub_segment"}
    for account in accounts:
        assert required <= account["registry"].keys(), "registry schema incomplete"
        assert account["events"], "an account must have events"
    # Signal check: churned accounts carry more escalations than retained ones.
    def esc_rate(acct):
        events = acct["events"]
        return sum(e["event_type"] == "escalation" for e in events) / len(events)
    churned = [a for a in accounts if a["label"]["churned"]]
    retained = [a for a in accounts if not a["label"]["churned"]]
    assert churned and retained, "need both classes"
    mean_c = sum(esc_rate(a) for a in churned) / len(churned)
    mean_r = sum(esc_rate(a) for a in retained) / len(retained)
    assert mean_c > mean_r, f"churned must escalate more (got {mean_c:.2f} vs {mean_r:.2f})"
    print(f"self-test OK: {len(churned)} churned / {len(retained)} retained; "
          f"escalation rate churned {mean_c:.2f} > retained {mean_r:.2f} (signal present).")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--self-test", action="store_true",
                        help="offline: schema completeness + churn signal (no DB/API)")
    parser.add_argument("--dry-run", action="store_true",
                        help="print the DDL + one sample account (no DB/API)")
    parser.add_argument("--accounts", type=int, default=500)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--database",
                        help=f"target Postgres DB (default: DATABASE_URL / PGDATABASE / "
                             f"{DEFAULT_DATABASE})")
    parser.add_argument("--realistic", action="store_true",
                        help="generate comm text with a frontier model (OpenRouter)")
    args = parser.parse_args()

    if args.self_test:
        return self_test()

    rng = random.Random(args.seed)
    if args.dry_run:
        print(SCHEMA_DDL)
        print("\n-- sample account --")
        print(json.dumps(synth_account(rng, 0), indent=2, default=str))
        return 0

    accounts = [synth_account(rng, i, realistic=args.realistic)
                for i in range(args.accounts)]
    insert(accounts, args.database)
    churned = sum(a["label"]["churned"] for a in accounts)
    print(f"inserted {len(accounts)} accounts ({churned} churned) into Postgres.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
